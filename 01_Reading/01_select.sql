-- Consulta 1:
-- SELECT * FROM users;
-- Esta consulta devuelve todas las columnas y todos los registros de la tabla users.
-- Se usa cuando queremos ver el contenido completo de la tabla.
SELECT * FROM users;

-- Consulta 2:
-- SELECT name FROM users;
-- Esta consulta muestra únicamente la columna name de todos los usuarios.
-- Es útil cuando solo necesitamos un dato concreto y no todo el registro.
SELECT name FROM users;

-- Consulta 3:
-- SELECT user_id, name FROM users;
-- Esta consulta devuelve solo las columnas user_id y name.
-- Se emplea para visualizar únicamente los campos relevantes de la tabla.
SELECT user_id, name FROM users;