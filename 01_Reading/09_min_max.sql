-- Consulta 1:
-- SELECT MAX(age) FROM users;
-- Devuelve la edad más alta que existe en la tabla users.
-- MAX() es una función agregada que obtiene el valor máximo de una columna.
SELECT MAX(age) FROM users;

-- Consulta 2:
-- SELECT MIN(age) FROM users;
-- Devuelve la edad más baja que existe en la tabla users.
-- MIN() obtiene el valor mínimo de una columna.
SELECT MIN(age) FROM users;

